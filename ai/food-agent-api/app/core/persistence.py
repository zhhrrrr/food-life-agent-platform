"""One SQL backend for checkpoints, receipts, leases and memory delivery jobs."""

import sqlite3
import threading
from contextlib import ExitStack, closing, contextmanager
from pathlib import Path


class RuntimeDatabase:
    def __init__(self, location: str):
        self.postgres = location.startswith(("postgresql://", "postgres://"))
        self.location = location if self.postgres else str(Path(location).resolve())
        if not self.postgres:
            Path(self.location).parent.mkdir(parents=True, exist_ok=True)
        self._stack = ExitStack()
        self._pool = None
        self._lock = threading.Lock()

    def pool(self):
        with self._lock:
            if self._pool is None:
                from psycopg.rows import dict_row
                from psycopg_pool import ConnectionPool

                self._pool = self._stack.enter_context(
                    ConnectionPool(
                        self.location,
                        min_size=1,
                        max_size=8,
                        timeout=10,
                        kwargs={
                            "autocommit": True,
                            "prepare_threshold": 0,
                            "row_factory": dict_row,
                            "connect_timeout": 5,
                        },
                    )
                )
        return self._pool

    @contextmanager
    def connect(self):
        if self.postgres:
            with self.pool().connection() as connection, connection.transaction():
                wrapper = _PostgresConnection(connection)
                try:
                    yield wrapper
                finally:
                    wrapper.close()
        else:
            with (
                closing(sqlite3.connect(self.location, timeout=10)) as connection,
                connection,
            ):
                yield connection

    def checkpointer(self):
        if self.postgres:
            from langgraph.checkpoint.postgres import PostgresSaver

            saver = PostgresSaver(self.pool())
            with self.pool().connection() as connection:
                connection.execute("SELECT pg_advisory_lock(6014777)")
                try:
                    saver.setup()
                finally:
                    connection.execute("SELECT pg_advisory_unlock(6014777)")
            return saver
        from langgraph.checkpoint.sqlite import SqliteSaver

        connection = self._stack.enter_context(
            closing(
                sqlite3.connect(
                    self.location,
                    check_same_thread=False,
                    timeout=10,
                )
            )
        )
        connection.execute("PRAGMA journal_mode=WAL")
        return SqliteSaver(connection)

    def close(self):
        self._stack.close()


class _PostgresConnection:
    """The application uses fixed qmark SQL; checkpoints use psycopg directly."""

    def __init__(self, connection):
        self.connection = connection
        self.cursors = []

    def execute(self, sql, parameters=()):
        from psycopg.rows import tuple_row

        cursor = self.connection.cursor(row_factory=tuple_row)
        self.cursors.append(cursor)
        return cursor.execute(sql.replace("?", "%s"), parameters)

    def executescript(self, sql):
        self.execute("SELECT pg_advisory_xact_lock(6014777)")
        sql = sql.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
        sql = sql.replace(" REAL", " DOUBLE PRECISION")
        for statement in sql.split(";"):
            if statement.strip():
                self.execute(statement)

    def close(self):
        for cursor in self.cursors:
            cursor.close()
